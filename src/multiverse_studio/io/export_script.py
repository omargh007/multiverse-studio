"""Export a session as a standalone, runnable Python script. Owner: A (Core).

The script uses only the public core API, so running it reproduces every number
in the GUI. This is how a no-code analysis becomes reproducible code.
"""

from __future__ import annotations

import pprint
from datetime import datetime, timezone
from pathlib import Path

from .. import __version__
from ..core.serialize import answers_to_dict, decision_to_dict
from ..core.types import Session

TEMPLATE = '''"""Reproduce a Multiverse Studio analysis.

Generated by Multiverse Studio {version} on {generated}.
Question: does {x!r} affect {y!r}?   Model: {family}
{blind_line}
Run:  python {script_name}
Needs: pip install multiverse-studio=={version}
"""

from multiverse_studio.core import api
from multiverse_studio.core.serialize import answers_from_dict, decision_from_dict
from multiverse_studio.io.loaders import load_table

DATA_FILE = {data_path!r}
Y = {y!r}
X = {x!r}
FAMILY = {family!r}
SEED = {seed!r}
ALPHA = {alpha!r}
MAX_SPECS = {max_specs!r}
SAMPLE_IF_OVER = {sample_if_over!r}
N_PERMUTATIONS = {n_permutations!r}

DECISIONS = {decisions}

GUARDRAIL_ANSWERS = {guardrails}


def main() -> None:
    df = load_table(DATA_FILE)
    decisions = [decision_from_dict(d) for d in DECISIONS]
    specs = api.build_specs(
        decisions, max_specs=MAX_SPECS, sample_if_over=SAMPLE_IF_OVER, seed=SEED
    )
    results = api.run_multiverse(df, Y, X, FAMILY, decisions, specs, alpha=ALPHA)

    assessments = api.assess_controls(
        {{name: answers_from_dict(a) for name, a in GUARDRAIL_ANSWERS.items()}}
    )
    results = api.mark_validity(results, decisions, assessments)

    perm_p = None
    if N_PERMUTATIONS:
        perm_p = api.permutation_test(
            df, Y, X, FAMILY, decisions, specs, results,
            n_permutations=N_PERMUTATIONS, alpha=ALPHA, seed=SEED,
        )
    verdict = api.summarize(results, alpha=ALPHA, permutation_p=perm_p)

    print(f"Verdict: {{verdict.label}}")
    print(verdict.explanation)
    for name, score in api.decision_importance(results, decisions).items():
        print(f"  {{name:<20}} explains {{score:.0%}} of the variation")


if __name__ == "__main__":
    main()
'''


def render_script(session: Session, script_name: str = "reproduce_analysis.py") -> str:
    """Return the script text (imports, data path, decisions, seed, run, summary)."""
    if not (session.y and session.x and session.family and session.data_path):
        raise ValueError("Load data and choose an outcome and a factor before exporting.")
    blind_line = (
        f"Plan locked (blind mode): sha256 {session.blind.sha256} at {session.blind.locked_at}\n"
        if session.blind
        else ""
    )
    return TEMPLATE.format(
        version=__version__,
        generated=datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        x=session.x,
        y=session.y,
        family=session.family,
        blind_line=blind_line,
        script_name=script_name,
        data_path=str(session.data_path),
        seed=session.seed,
        alpha=session.alpha,
        max_specs=session.max_specs,
        sample_if_over=session.sample_if_over,
        n_permutations=session.n_permutations,
        decisions=pprint.pformat(
            [decision_to_dict(d) for d in session.decisions], indent=4, width=88, sort_dicts=False
        ),
        guardrails=pprint.pformat(
            {k: answers_to_dict(v) for k, v in session.guardrails.items()}, indent=4, width=88
        ),
    )


def export_script(session: Session, path: str | Path) -> Path:
    path = Path(path)
    path.write_text(render_script(session, script_name=path.name), encoding="utf-8")
    return path
